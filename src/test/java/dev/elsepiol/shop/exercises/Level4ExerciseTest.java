@Tag("exercise")
@SpringBootTest
@AutoConfigureMockMvc
class Level4ExerciseTest extends PostgresIntegrationTest {

	@Autowired
	private MockMvc mvc;

	@Autowired
	private NamedParameterJdbcTemplate jdbc;

	@Autowired
	private PlatformTransactionManager transactionManager;

	private ApiClient api;

	@BeforeEach
	void setUp() {
		api = new ApiClient(mvc);
	}

	/** Places n orders for this user and returns their ids, oldest first. */
	private List<Long> placeOrders(Account who, long product, int n) throws Exception {
		List<Long> ids = new ArrayList<>();
		for (int i = 0; i < n; i++) {
			String body = api.placeOrder(who, ApiClient.newKey(), product, 1).andExpect(status().isCreated())
					.andReturn().getResponse().getContentAsString();
			ids.add(((Number) JsonPath.read(body, "$.id")).longValue());
		}
		return ids;
	}

	/** One page of GET /api/v1/orders/scroll as raw JSON. A null cursor means the first page. */
	private String page(Account who, String cursor, int size) throws Exception {
		var request = get("/api/v1/orders/scroll").header("Authorization", who.bearer()).param("size",
				String.valueOf(size));
		if (cursor != null) {
			request = request.param("cursor", cursor);
		}
		return mvc.perform(request).andExpect(status().isOk()).andReturn().getResponse().getContentAsString();
	}

	private static List<Long> ids(String page) {
		List<Number> ids = JsonPath.read(page, "$.items[*].id");
		return ids.stream().map(Number::longValue).toList();
	}

	// ---- Part A: GET /api/v1/orders/scroll?size=N&cursor=...  (keyset pagination, newest first) ----

	@Test
	void scrollWalksAllMyOrdersNewestFirstAndNothingElse() throws Exception {
		Account alice = api.newUser();
		Account bob = api.newUser();
		long mug = api.newProductWithStock(100, 50);
		List<Long> mine = placeOrders(alice, mug, 7);
		placeOrders(bob, mug, 2);

		String first = page(alice, null, 3);
		String second = page(alice, JsonPath.read(first, "$.nextCursor"), 3);
		String third = page(alice, JsonPath.read(second, "$.nextCursor"), 3);

		List<Long> newestFirst = new ArrayList<>(mine);
		Collections.reverse(newestFirst);
		assertThat(ids(first)).isEqualTo(newestFirst.subList(0, 3));
		assertThat(ids(second)).isEqualTo(newestFirst.subList(3, 6));
		assertThat(ids(third)).isEqualTo(newestFirst.subList(6, 7));
		assertThat((Object) JsonPath.read(third, "$.nextCursor")).as("no page after the last one").isNull();
	}

	/** The bug OrderApiTest.offsetPagesShiftWhenANewOrderArrivesWhilePaging shows, fixed. */
	@Test
	void anOrderPlacedWhileScrollingDoesNotShowUpTwice() throws Exception {
		Account alice = api.newUser();
		long mug = api.newProductWithStock(100, 50);
		List<Long> mine = placeOrders(alice, mug, 6);

		String first = page(alice, null, 3);
		placeOrders(alice, mug, 1); // arrives while the customer is reading page 1
		String second = page(alice, JsonPath.read(first, "$.nextCursor"), 3);

		assertThat(ids(second)).as("exactly the three oldest, nothing repeated")
				.containsExactly(mine.get(2), mine.get(1), mine.get(0));
	}

	@Test
	void eachOrderInTheScrollHasItsItems() throws Exception {
		Account alice = api.newUser();
		long mug = api.newProductWithStock(250, 50);
		placeOrders(alice, mug, 2);

		String first = page(alice, null, 10);

		assertThat(ids(first)).hasSize(2);
		assertThat((Integer) JsonPath.read(first, "$.items[0].items[0].unitPriceCents")).isEqualTo(250);
	}

	// ---- Part B: an index that matches "my orders, newest first" ----

	/**
	 * EXPLAINs the two queries behind "my orders, newest first" on a table of 50,000 orders
	 * (500 users x 100), inside a transaction that is rolled back afterwards. Both must be read
	 * straight out of an index in the right order: no Sort node, and both conditions answered
	 * by the index.
	 */
	@Test
	void newestFirstQueriesAreServedByAnIndexWithoutSorting() {
		TransactionTemplate tx = new TransactionTemplate(transactionManager);
		List<QueryPlan> plans = tx.execute(status -> {
			status.setRollbackOnly();
			String token = UUID.randomUUID().toString().substring(0, 8);
			jdbc.update("""
					insert into users (email, password_hash, role)
					select 'ex4-' || g || '-' || :token || '@example.com', 'not-a-hash', 'USER'
					from generate_series(1, 500) g""", Map.of("token", token));
			jdbc.update("""
					insert into orders (user_id, status, total_cents, idempotency_key, request_hash)
					select u.id, 'PLACED', 100, 'ex4-' || g, 'hash'
					from users u cross join generate_series(1, 100) g
					where u.email like 'ex4-%-' || :token || '@example.com'""", Map.of("token", token));
			jdbc.getJdbcTemplate().execute("analyze orders");
			Long someone = jdbc.queryForObject("select min(id) from users where email like 'ex4-%-' || :token || '%'",
					Map.of("token", token), Long.class);
			Long middle = jdbc.queryForObject("select percentile_disc(0.5) within group (order by id) from orders "
					+ "where user_id = :u", Map.of("u", someone), Long.class);
			return List.of(
					// the first page (this is also what GET /api/v1/orders runs)
					QueryPlan.explain(jdbc, "select * from orders where user_id = :u order by id desc limit 11",
							Map.of("u", someone), false),
					// a later page: the orders older than the cursor
					QueryPlan.explain(jdbc,
							"select * from orders where user_id = :u and id < :before order by id desc limit 11",
							Map.of("u", someone, "before", middle), false));
		});

		for (QueryPlan plan : plans) {
			assertThat(plan.nodeTypes()).as(plan.toString()).doesNotContain("Sort", "Incremental Sort", "Seq Scan");
			assertThat(plan.indexConditions()).as(plan.toString()).singleElement().asString().contains("user_id");
		}
		assertThat(plans.get(1).indexConditions()).as(plans.get(1).toString()).singleElement().asString()
				.contains("id <");
	}

	/** Every index slows down every INSERT into the table. One that no query needs is pure cost. */
	@Test
	void theIndexNoQueryUsesAnyMoreIsDropped() {
		Integer count = jdbc.queryForObject("select count(*) from pg_indexes where indexname = 'idx_orders_user_created'",
				Map.of(), Integer.class);

		assertThat(count).isZero();
	}

}
