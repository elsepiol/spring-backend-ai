package dev.elsepiol.shop.exercises;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.content;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import dev.elsepiol.shop.product.ProductService;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.WebMvcTest;
import org.springframework.http.MediaType;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.web.servlet.MockMvc;

/**
 * EXERCISE 0 - your turn. See docs/learn/00-orientation.md, section "Exercise 0".
 *
 * These tests are tagged "exercise", so the normal build skips them. Run them with:
 *     ./mvnw test -Pexercises        (Windows: mvnw.cmd test -Pexercises)
 * They fail until you write the controller. Do not edit this file to make them pass.
 */
@Tag("exercise")
@WebMvcTest
class Level0GreetingExerciseTest {

	@Autowired
	private MockMvc mockMvc;

	// @WebMvcTest loads every controller. ProductController needs a ProductService,
	// which this web-only test does not start, so we provide a stand-in. Ignore it.
	@MockitoBean
	private ProductService productService;

	@Test
	void greetsAValidName() throws Exception {
		mockMvc.perform(get("/api/v1/greetings/Anurag"))
				.andExpect(status().isOk())
				.andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_JSON))
				.andExpect(jsonPath("$.message").value("Hello, Anurag!"));
	}

	@Test
	void rejectsANameThatIsTooShort() throws Exception {
		mockMvc.perform(get("/api/v1/greetings/A"))
				.andExpect(status().isBadRequest());
	}

	@Test
	void rejectsANameWithDigits() throws Exception {
		mockMvc.perform(get("/api/v1/greetings/An1"))
				.andExpect(status().isBadRequest());
	}

	@Test
	void rejectsANameThatIsTooLong() throws Exception {
		String tooLong = "a".repeat(31);
		mockMvc.perform(get("/api/v1/greetings/" + tooLong))
				.andExpect(status().isBadRequest());
	}

}
