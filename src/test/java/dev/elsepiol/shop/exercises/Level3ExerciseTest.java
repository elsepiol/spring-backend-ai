/**
 * EXERCISE 3 - your turn. See docs/learn/03-orders-and-concurrency.md, section "Exercise 3".
 *
 * Needs Docker running. Run with:  ./mvnw test -Pexercises
 * Do not edit this file to make the tests pass.
 */
@Tag("exercise")
@SpringBootTest
@AutoConfigureMockMvc
class Level3ExerciseTest extends PostgresIntegrationTest {

	@Autowired
	private MockMvc mvc;

	private ApiClient api;

	@BeforeEach
	void setUp() {
		api = new ApiClient(mvc);
	}

	// ---- Part A: GET /api/v1/admin/inventory/low-stock?threshold=N  (ADMIN only) ----

	@Test
	void lowStockListsProductsAtOrBelowTheThresholdLowestFirst() throws Exception {
		long empty = api.newProductWithStock(100, 0);
		long few = api.newProductWithStock(100, 3);
		long plenty = api.newProductWithStock(100, 900_000);

		String body = mvc.perform(get("/api/v1/admin/inventory/low-stock").with(admin()).param("threshold", "5"))
				.andExpect(status().isOk())
				.andReturn().getResponse().getContentAsString();

		List<Integer> ids = com.jayway.jsonpath.JsonPath.read(body, "$[*].productId");
		assertThat(ids).contains((int) empty, (int) few).doesNotContain((int) plenty);
		assertThat(ids.indexOf((int) empty)).as("lowest stock first").isLessThan(ids.indexOf((int) few));
		mvc.perform(get("/api/v1/admin/inventory/low-stock").with(admin()).param("threshold", "5"))
				.andExpect(jsonPath("$[?(@.productId == " + few + ")].quantity").value(3));
	}

	@Test
	void lowStockIsForAdminsOnly() throws Exception {
		mvc.perform(get("/api/v1/admin/inventory/low-stock")).andExpect(status().isUnauthorized());
		mvc.perform(get("/api/v1/admin/inventory/low-stock").with(user())).andExpect(status().isForbidden());
	}

	// ---- Part B: POST /api/v1/products/{id}/stock/adjust  {"delta": n} ----

	private int adjust(long productId, int delta) throws Exception {
		return mvc.perform(post("/api/v1/products/" + productId + "/stock/adjust").with(admin())
				.contentType(MediaType.APPLICATION_JSON).content("{\"delta\":" + delta + "}"))
				.andReturn().getResponse().getStatus();
	}

	@Test
	void adjustAddsAndRemovesStock() throws Exception {
		long id = api.newProductWithStock(100, 10);

		assertThat(adjust(id, 5)).isEqualTo(204);
		assertThat(api.stockOf(id)).isEqualTo(15);
		assertThat(adjust(id, -15)).isEqualTo(204);
		assertThat(api.stockOf(id)).isZero();
	}

	@Test
	void adjustBelowZeroIs409AndLeavesStockAlone() throws Exception {
		long id = api.newProductWithStock(100, 3);

		assertThat(adjust(id, -4)).isEqualTo(409);
		assertThat(api.stockOf(id)).isEqualTo(3);
	}

	@Test
	void adjustWithoutAStockRecordIs404() throws Exception {
		long noStockRow = api.newProduct(100);

		assertThat(adjust(noStockRow, 1)).isEqualTo(404);
		assertThat(adjust(987654321L, 1)).isEqualTo(404);
	}

	@Test
	void aDeltaOfZeroIs400() throws Exception {
		long id = api.newProductWithStock(100, 3);

		assertThat(adjust(id, 0)).isEqualTo(400);
	}

	@Test
	void adjustIsAdminOnly() throws Exception {
		long id = api.newProductWithStock(100, 3);

		mvc.perform(post("/api/v1/products/" + id + "/stock/adjust").contentType(MediaType.APPLICATION_JSON)
				.content("{\"delta\":1}")).andExpect(status().isUnauthorized());
		mvc.perform(post("/api/v1/products/" + id + "/stock/adjust").with(user())
				.contentType(MediaType.APPLICATION_JSON).content("{\"delta\":1}")).andExpect(status().isForbidden());
	}

	/** The real point of Part B: 20 simultaneous "take one" calls on a stock of 10. */
	@Test
	void twentySimultaneousAdjustmentsOnTenItemsNeverOversell() throws Exception {
		long id = api.newProductWithStock(100, 10);

		List<Object> statuses = Concurrently.runAtOnce(20, i -> () -> adjust(id, -1));

		assertThat(statuses.stream().filter(s -> s.equals(204)).count()).as("succeeded").isEqualTo(10);
		assertThat(statuses.stream().filter(s -> s.equals(409)).count()).as("refused").isEqualTo(10);
		assertThat(api.stockOf(id)).isZero();
	}

}
