@Tag("exercise")
@SpringBootTest
@AutoConfigureMockMvc
@AutoConfigureTracing
class Level6ExerciseTest extends PostgresIntegrationTest {

	@Autowired
	private MockMvc mvc;

	@Autowired
	private MeterRegistry meters;

	@Autowired
	private JdbcTemplate jdbc;

	private double gauge(String name) {
		RequiredSearch search = meters.get(name);
		return search.gauge().value();
	}

	private void addEvent(String status, String age) {
		jdbc.update("insert into outbox_events (type, aggregate_id, payload, status, created_at) "
				+ "values ('test.metrics', 0, '{}', ?, now() - ?::interval)", status, age);
	}

	// ---- Part A: outbox backlog gauges ----

	@Test
	void pendingEventsAreCounted() {
		double before = gauge("shop.outbox.pending");

		addEvent("PENDING", "1 second");
		addEvent("PENDING", "1 second");

		assertThat(gauge("shop.outbox.pending")).isEqualTo(before + 2);
	}

	@Test
	void deadEventsAreCounted() {
		double before = gauge("shop.outbox.dead");

		addEvent("DEAD", "1 second");

		assertThat(gauge("shop.outbox.dead")).isEqualTo(before + 1);
	}

	/** Depth is not enough: 10 events waiting 2 seconds is fine, 10 waiting an hour is an incident. */
	@Test
	void theAgeOfTheOldestPendingEventIsReportedInSeconds() {
		addEvent("PENDING", "3 hours");

		assertThat(gauge("shop.outbox.oldest.pending.age")).isGreaterThanOrEqualTo(3 * 3600);
	}

	@Test
	void theGaugesAreVisibleToPrometheus() throws Exception {
		String scrape = mvc.perform(get("/actuator/metrics/shop.outbox.pending").with(admin()))
				.andExpect(status().isOk()).andReturn().getResponse().getContentAsString();

		assertThat(scrape).contains("\"name\":\"shop.outbox.pending\"");
	}

	// ---- Part B: every error body carries the trace id ----

	@Test
	void aNotFoundErrorCarriesTheTraceIdOfTheCallersTrace() throws Exception {
		mvc.perform(get("/api/v1/products/987654321")
				.header("traceparent", "00-0af7651916cd43dd8448eb211c80319c-b7ad6b7169203331-01"))
				.andExpect(status().isNotFound())
				.andExpect(jsonPath("$.traceId").value("0af7651916cd43dd8448eb211c80319c"));
	}

	@Test
	void aValidationErrorCarriesTheSameTraceIdAsItsHeader() throws Exception {
		MvcResult result = mvc.perform(post("/api/v1/products").with(admin()).contentType(MediaType.APPLICATION_JSON)
				.content("{\"sku\":\"bad sku!\",\"name\":\"\",\"priceCents\":-5}"))
				.andExpect(status().isBadRequest())
				.andReturn();

		String header = result.getResponse().getHeader("X-Trace-Id");
		assertThat(header).isNotBlank();
		assertThat(com.jayway.jsonpath.JsonPath.<String>read(result.getResponse().getContentAsString(), "$.traceId"))
				.isEqualTo(header);
	}

}
