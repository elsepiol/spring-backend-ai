package dev.elsepiol.shop.exercises;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.jayway.jsonpath.JsonPath;
import dev.elsepiol.shop.support.PostgresIntegrationTest;
import java.util.UUID;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.MockMvc;

/**
 * EXERCISE 2 - your turn. See docs/learn/02-security.md, section "Exercise 2".
 *
 * Needs Docker running. Run with:  ./mvnw test -Pexercises
 * These tests use REAL registration, login and tokens. Do not edit this file to make them pass.
 */
@Tag("exercise")
@SpringBootTest
@AutoConfigureMockMvc
class Level2ExerciseTest extends PostgresIntegrationTest {

	private static final String PASSWORD = "correct horse battery";

	@Autowired
	private MockMvc mockMvc;

	private static String uniqueEmail() {
		return "ex2-" + UUID.randomUUID().toString().substring(0, 8) + "@example.com";
	}

	/** Registers a new user and returns the email. */
	private String registered() throws Exception {
		String email = uniqueEmail();
		mockMvc.perform(post("/api/v1/auth/register").contentType(MediaType.APPLICATION_JSON)
				.content("{\"email\":\"" + email + "\",\"password\":\"" + PASSWORD + "\"}"))
				.andExpect(status().isCreated());
		return email;
	}

	private String tokenFor(String email, String password) throws Exception {
		String body = mockMvc.perform(post("/api/v1/auth/login").contentType(MediaType.APPLICATION_JSON)
				.content("{\"email\":\"" + email + "\",\"password\":\"" + password + "\"}"))
				.andExpect(status().isOk())
				.andReturn()
				.getResponse()
				.getContentAsString();
		return JsonPath.read(body, "$.accessToken");
	}

	private String changeBody(String current, String next) {
		return "{\"currentPassword\":\"" + current + "\",\"newPassword\":\"" + next + "\"}";
	}

	// ---- Part A: GET /api/v1/me  (who am I, read from the token, no database call) ----

	@Test
	void meReturnsTheCallersIdentity() throws Exception {
		String email = registered();
		String token = tokenFor(email, PASSWORD);

		mockMvc.perform(get("/api/v1/me").header("Authorization", "Bearer " + token))
				.andExpect(status().isOk())
				.andExpect(jsonPath("$.id").isNumber())
				.andExpect(jsonPath("$.email").value(email))
				.andExpect(jsonPath("$.role").value("USER"));
	}

	@Test
	void meWithoutATokenIs401() throws Exception {
		mockMvc.perform(get("/api/v1/me")).andExpect(status().isUnauthorized());
	}

	// ---- Part B: POST /api/v1/auth/change-password ----

	@Test
	void changingThePasswordMakesTheOldOneStopWorking() throws Exception {
		String email = registered();
		String token = tokenFor(email, PASSWORD);

		mockMvc.perform(post("/api/v1/auth/change-password").header("Authorization", "Bearer " + token)
				.contentType(MediaType.APPLICATION_JSON)
				.content(changeBody(PASSWORD, "a brand new passphrase")))
				.andExpect(status().isNoContent());

		mockMvc.perform(post("/api/v1/auth/login").contentType(MediaType.APPLICATION_JSON)
				.content("{\"email\":\"" + email + "\",\"password\":\"" + PASSWORD + "\"}"))
				.andExpect(status().isUnauthorized());
		tokenFor(email, "a brand new passphrase"); // the new password works
	}

	@Test
	void aWrongCurrentPasswordIsRejectedWith400() throws Exception {
		String email = registered();
		String token = tokenFor(email, PASSWORD);

		mockMvc.perform(post("/api/v1/auth/change-password").header("Authorization", "Bearer " + token)
				.contentType(MediaType.APPLICATION_JSON)
				.content(changeBody("not my password!!", "a brand new passphrase")))
				.andExpect(status().isBadRequest());

		tokenFor(email, PASSWORD); // nothing changed
	}

	@Test
	void aTooShortNewPasswordIsRejectedWith400() throws Exception {
		String email = registered();
		String token = tokenFor(email, PASSWORD);

		mockMvc.perform(post("/api/v1/auth/change-password").header("Authorization", "Bearer " + token)
				.contentType(MediaType.APPLICATION_JSON)
				.content(changeBody(PASSWORD, "short")))
				.andExpect(status().isBadRequest());
	}

	@Test
	void changingThePasswordWithoutATokenIs401() throws Exception {
		mockMvc.perform(post("/api/v1/auth/change-password").contentType(MediaType.APPLICATION_JSON)
				.content(changeBody(PASSWORD, "a brand new passphrase")))
				.andExpect(status().isUnauthorized());
	}

}
