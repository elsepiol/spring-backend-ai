package dev.elsepiol.shop.exercises;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.delete;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import dev.elsepiol.shop.support.PostgresIntegrationTest;
import java.util.UUID;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.MockMvc;

/**
 * EXERCISE 1 - your turn. See docs/learn/01-persistence.md, section "Exercise 1".
 *
 * Needs Docker running (a real PostgreSQL is started for you). Run with:
 *     ./mvnw test -Pexercises
 * Do not edit this file to make the tests pass.
 */
@Tag("exercise")
@SpringBootTest
@AutoConfigureMockMvc
class Level1ExerciseTest extends PostgresIntegrationTest {

	@Autowired
	private MockMvc mockMvc;

	/** Creates a product and returns its Location header (/api/v1/products/{id}). */
	private String create(String name) throws Exception {
		String sku = "EX-" + UUID.randomUUID().toString().replace("-", "").substring(0, 12).toUpperCase();
		String body = "{\"sku\":\"" + sku + "\",\"name\":\"" + name + "\",\"priceCents\":1000}";
		return mockMvc.perform(post("/api/v1/products").contentType(MediaType.APPLICATION_JSON).content(body))
				.andExpect(status().isCreated())
				.andReturn()
				.getResponse()
				.getHeader("Location");
	}

	private String token() {
		return UUID.randomUUID().toString().replace("-", "").substring(0, 10);
	}

	// ---- Part A: DELETE /api/v1/products/{id} ----

	@Test
	void deleteRemovesTheProduct() throws Exception {
		String location = create("To delete " + token());

		mockMvc.perform(delete(location)).andExpect(status().isNoContent());
		mockMvc.perform(get(location)).andExpect(status().isNotFound());
	}

	@Test
	void deletingAnUnknownProductReturns404() throws Exception {
		mockMvc.perform(delete("/api/v1/products/987654321")).andExpect(status().isNotFound());
	}

	// ---- Part B: GET /api/v1/products/search?q=...  (name contains q, ignoring case, paged) ----

	@Test
	void searchFindsByNameIgnoringCase() throws Exception {
		String t = token();
		create("Blue MUG " + t);
		create("red mug " + t);
		create("Green plate " + t);

		mockMvc.perform(get("/api/v1/products/search").param("q", "mug " + t))
				.andExpect(status().isOk())
				.andExpect(jsonPath("$.totalElements").value(2))
				.andExpect(jsonPath("$.items.length()").value(2));
	}

	@Test
	void searchIsPaged() throws Exception {
		String t = token();
		create("Spoon one " + t);
		create("Spoon two " + t);
		create("Spoon three " + t);

		mockMvc.perform(get("/api/v1/products/search").param("q", t).param("size", "2").param("page", "1"))
				.andExpect(status().isOk())
				.andExpect(jsonPath("$.items.length()").value(1))
				.andExpect(jsonPath("$.totalElements").value(3))
				.andExpect(jsonPath("$.totalPages").value(2));
	}

	@Test
	void searchWithNoMatchReturnsAnEmptyPage() throws Exception {
		mockMvc.perform(get("/api/v1/products/search").param("q", "zz-" + token()))
				.andExpect(status().isOk())
				.andExpect(jsonPath("$.totalElements").value(0))
				.andExpect(jsonPath("$.items.length()").value(0));
	}

}
