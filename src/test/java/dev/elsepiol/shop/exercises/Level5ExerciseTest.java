package dev.elsepiol.shop.exercises;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.jayway.jsonpath.JsonPath;
import dev.elsepiol.shop.order.OrderEvent;
import dev.elsepiol.shop.outbox.OutboxWorker;
import dev.elsepiol.shop.support.ApiClient;
import dev.elsepiol.shop.support.ApiClient.Account;
import dev.elsepiol.shop.support.PostgresIntegrationTest;
import java.util.List;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.TestPropertySource;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;

/**
 * EXERCISE 5 - your turn. See docs/learn/05-scaling-out.md, section "Exercise 5".
 *
 * Needs Docker running. Run with:  ./mvnw test -Pexercises
 * Do not edit this file to make the tests pass.
 */
@Tag("exercise")
@SpringBootTest
@AutoConfigureMockMvc
@TestPropertySource(properties = { "app.rate-limit.orders.capacity=3", "app.rate-limit.orders.period=1m" })
class Level5ExerciseTest extends PostgresIntegrationTest {

	@Autowired
	private MockMvc mvc;

	@Autowired
	private OutboxWorker worker;

	@Autowired
	private JdbcTemplate jdbc;

	private ApiClient api;

	@BeforeEach
	void setUp() {
		api = new ApiClient(mvc);
	}

	private void drainOutbox() {
		while (worker.runOnce() > 0) {
			// until nothing is due
		}
	}

	private List<String> notificationsOf(Account who) throws Exception {
		String body = mvc.perform(get("/api/v1/notifications").header("Authorization", who.bearer()))
				.andExpect(status().isOk()).andReturn().getResponse().getContentAsString();
		return JsonPath.read(body, "$[*].message");
	}

	// ---- Part A: at most app.rate-limit.orders.capacity orders per period, per user ----

	@Test
	void aUserWhoPlacesTooManyOrdersGets429WithRetryAfter() throws Exception {
		Account alice = api.newUser();
		long mug = api.newProductWithStock(100, 50);
		for (int i = 0; i < 3; i++) {
			api.placeOrder(alice, ApiClient.newKey(), mug, 1).andExpect(status().isCreated());
		}

		MvcResult refused = api.placeOrder(alice, ApiClient.newKey(), mug, 1)
				.andExpect(status().isTooManyRequests()).andReturn();

		assertThat(refused.getResponse().getHeader("Retry-After")).isEqualTo("20"); // 3 per minute
		assertThat(api.stockOf(mug)).as("the refused order took no stock").isEqualTo(47);
	}

	@Test
	void theLimitIsPerUserNotShared() throws Exception {
		Account alice = api.newUser();
		Account bob = api.newUser();
		long mug = api.newProductWithStock(100, 50);
		for (int i = 0; i < 3; i++) {
			api.placeOrder(alice, ApiClient.newKey(), mug, 1).andExpect(status().isCreated());
		}

		api.placeOrder(bob, ApiClient.newKey(), mug, 1).andExpect(status().isCreated());
	}

	@Test
	void readingOrdersIsNotLimited() throws Exception {
		Account alice = api.newUser();
		long mug = api.newProductWithStock(100, 50);
		for (int i = 0; i < 3; i++) {
			api.placeOrder(alice, ApiClient.newKey(), mug, 1).andExpect(status().isCreated());
		}

		for (int i = 0; i < 5; i++) {
			mvc.perform(get("/api/v1/orders").header("Authorization", alice.bearer())).andExpect(status().isOk());
		}
	}

	// ---- Part B: an OrderCancelled handler that notifies the customer, exactly once ----

	private long placeAndCancel(Account who) throws Exception {
		long mug = api.newProductWithStock(1500, 5);
		String body = api.placeOrder(who, ApiClient.newKey(), mug, 2).andExpect(status().isCreated())
				.andReturn().getResponse().getContentAsString();
		long orderId = ((Number) JsonPath.read(body, "$.id")).longValue();
		mvc.perform(post("/api/v1/orders/" + orderId + "/cancel").header("Authorization", who.bearer()))
				.andExpect(status().isOk());
		return orderId;
	}

	@Test
	void cancellingAnOrderNotifiesTheCustomer() throws Exception {
		Account alice = api.newUser();
		long orderId = placeAndCancel(alice);

		drainOutbox();

		assertThat(notificationsOf(alice)).contains("Order #" + orderId + " was cancelled.");
		assertThat(jdbc.queryForObject("select status from outbox_events where type = ? and aggregate_id = ?",
				String.class, OrderEvent.CANCELLED, orderId)).isEqualTo("DONE");
	}

	/** At-least-once delivery: the same event can arrive again. The customer must still get one message. */
	@Test
	void aRedeliveredCancellationStillNotifiesOnceAndSucceeds() throws Exception {
		Account alice = api.newUser();
		long orderId = placeAndCancel(alice);
		drainOutbox();

		jdbc.update("update outbox_events set status = 'PENDING', available_at = now() where type = ? and aggregate_id = ?",
				OrderEvent.CANCELLED, orderId);
		drainOutbox();

		assertThat(notificationsOf(alice).stream().filter(m -> m.contains("cancelled"))).hasSize(1);
		assertThat(jdbc.queryForObject("select status from outbox_events where type = ? and aggregate_id = ?",
				String.class, OrderEvent.CANCELLED, orderId)).as("handled again without an error").isEqualTo("DONE");
	}

}
